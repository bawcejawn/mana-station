describe("red team INSIDER: two colluding council members override the third member's veto", () => {
  it("an upgrade that one member vetoes can't become uploadable by removing that member first", () => {
    const s = setup(); gS = s;
    const r = buyAccount(s, U2, 10 * M, 7);                                         // buyer money in escrow
    expect(r.paid).toBeGreaterThan(0, "setup: escrow holds a buyer's payment");
    const evil = new Uint8Array(64); evil[0] = 66;
    const h = System.hash(Crypto.multicodec.sha2_256, evil)!;
    // Round 1: C1 + C2 approve the upgrade, C3 vetoes it.
    const a1 = act(1); a1.hash = h;
    signedBy([C1]); const id1 = s.propose(new station.propose_arguments(C1, a1)).id;
    signedBy([C2]); s.approve(new station.approve_arguments(C2, id1));
    signedBy([C3]); s.cancel_proposal(new station.cancel_proposal_arguments(C3, id1)); signedBy([]);
    at(NOW + 2 * DAYMS);
    expect(upAuthAll(s, evil)).toBe(false, "control: C3's veto stopped round 1");
    MockVM.clearEvents();                                                            // keep the MockVM event list short
    // Round 2: C1 + C2 remove C3 (replaced by their own key cm(4)); C3's veto of its own removal is refused (H1).
    const nc = act(4); nc.council = [C1, C2, cm(4)]; nc.threshold = 2;
    signedBy([C1]); const id2 = s.propose(new station.propose_arguments(C1, nc)).id; gId = id2;
    signedBy([C3]); MockVM.commitTransaction();
    clearRevert(); expect(() => { gS!.cancel_proposal(new station.cancel_proposal_arguments(C3, gId)); }).toThrow("setup (by design, H1): C3 can't veto its own removal"); revertedWith("a member can't veto their own removal");
    signedBy([C2]); s.approve(new station.approve_arguments(C2, id2)); signedBy([]);
    at(NOW + 2 * DAYMS); s.execute(new station.execute_arguments(id2));
    MockVM.clearEvents();
    // Round 3: the same upgrade again; nobody left can veto.
    // audit-fixes-1 adjustment: the fix REFUSES the attacker's setup step (it used to be accepted), so that step is now
    // asserted with toThrow instead of being run bare (a bare refused call aborts the test). Every original SAFE assertion is kept.
    const a3 = act(1); a3.hash = h; gA3 = a3;
    signedBy([C1]); MockVM.commitTransaction();
    clearRevert(); expect(() => { gS!.propose(new station.propose_arguments(C1, gA3)); })
      .toThrow("BROKEN: the vetoed upgrade was proposed again right after the vetoing member was removed"); revertedWith("an action of this kind was vetoed less than 14 days ago");
    signedBy([]);
    at(NOW + 2 * DAYMS);
    expect(upAuthAll(s, evil)).toBe(false,
      "BROKEN (terms.html:46 'any one member can veto'): C1 + C2 removed the vetoing member and now upload code C3 vetoed; that code can take the escrowed buyer funds");
  });
});
