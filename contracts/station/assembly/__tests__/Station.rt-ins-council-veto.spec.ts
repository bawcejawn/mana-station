/**
 * RED TEAM (INSIDER: two colluding council members out of 3, threshold 2). Attack: C1 + C2 want an upgrade to their own
 * code (which can take the escrowed buyer funds). C3 vetoes it. C1 + C2 then propose a council change that removes C3;
 * C3 can't veto their own removal (review H1, Station.ts:1309-1313). After 48 h C3 is out, and the same upgrade goes
 * through with nobody left able to veto. Total ~96 h, all public, but the honest member's veto is overridden.
 * Promise: site/src/terms.html:46 "a public waiting period (48 hours on mainnet) during which any one member can veto";
 * ALLOWANCE_TERMS / BIG_TERMS (Station.ts:59-60) "no veto from any member". LAUNCH.md:48 discloses the H1 exception, the
 * buyer-facing terms don't. The H1 exception is deliberate; the fix may be in the terms (disclose that a threshold of
 * members can remove a dissenter and then act) or in code (e.g. a longer wait for upgrades and money moves proposed
 * soon after a council change).
 * This test asserts the documented promise: it FAILS if broken (expected to fail on 4343f83).
 */
