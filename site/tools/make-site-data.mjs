// Writes the data files the pages load with plain <script> tags, so they also work opened from disk (file://):
//   site/abis.js        contract ABIs (station, demo app)
//   site/playground.js  the testnet playground's addresses (from testnet/playground.json, written by playground.mjs)
// Run after a contract change or a playground deploy:  node site/tools/make-site-data.mjs
import fs from "fs";
const rd = (p) => JSON.parse(fs.readFileSync(new URL(p, import.meta.url)));
const abis = { station: rd("../../contracts/station/abi/station.koilib.json"), app: rd("../../contracts/testapp/abi/testapp.koilib.json"), token: rd("../../contracts/mocktoken/abi/mocktoken.koilib.json") };
fs.writeFileSync(new URL("../abis.js", import.meta.url), "// Generated by site/tools/make-site-data.mjs. Do not edit.\nwindow.MS_ABI = " + JSON.stringify(abis) + ";\n");
let pg = {};
try { pg = rd("../../testnet/playground.json"); } catch { console.log("no testnet/playground.json yet: playground.js keeps placeholders"); }
const play = { network: "Koinos testnet", rpc: pg.network || "https://testnet.koinosfoundation.org", chainId: pg.chain_id || "", station: pg.station || "", demoApp: pg.demo_app || "", openApp: pg.open_app || "", testStablecoin: pg.test_stablecoin || "" };
fs.writeFileSync(new URL("../playground.js", import.meta.url), "// Generated by site/tools/make-site-data.mjs from testnet/playground.json. Testnet only.\nwindow.MS_PLAYGROUND = " + JSON.stringify(play, null, 2) + ";\n");
// The demo app's bytecode, so the buy page can upload "your app" with a big-upload ticket (testnet).
try {
  const code = fs.readFileSync(new URL("../../contracts/testapp/build/release/contract.wasm", import.meta.url));
  fs.writeFileSync(new URL("../app-code.js", import.meta.url), "// Generated by site/tools/make-site-data.mjs: the demo app's bytecode (base64).\nwindow.MS_APP_CODE = \"" + code.toString("base64") + "\";\n");
} catch { console.log("no testapp build: site/app-code.js not written (build contracts/testapp first)"); }
console.log("wrote site/abis.js and site/playground.js", play.station ? "(station " + play.station + ")" : "(no station yet)");
// A council-approved upgrade for the station (Owner page → Upgrades). audit-2026-10 M-10: offered ONLY for a tagged
// release whose fingerprint was published, never for whatever build happens to be on disk:
//   UPGRADE_TAG=release-2026-11-01 UPGRADE_SHA256=<sha256 from docs/LAUNCH.md> [UPGRADE_WASM=contracts/station/build/testnet/contract.wasm] \
//     node site/tools/make-site-data.mjs
// HEAD must be that tag's commit and the wasm's sha256 must equal UPGRADE_SHA256; otherwise no upgrade is offered.
{
  const out = new URL("../station-code.js", import.meta.url);
  const none = (why) => { fs.writeFileSync(out, "// Generated by site/tools/make-site-data.mjs: no upgrade offered (" + why + ").\nwindow.MS_UPGRADE = null;\n"); console.log("site/station-code.js: no upgrade offered (" + why + ")"); };
  const tag = process.env.UPGRADE_TAG || "", want = (process.env.UPGRADE_SHA256 || "").toLowerCase().replace(/^0x1220/, "");
  const wasmPath = new URL(process.env.UPGRADE_WASM ? "../../" + process.env.UPGRADE_WASM.replace(/^\.?\//, "") : "../../contracts/station/build/testnet/contract.wasm", import.meta.url);
  if (!tag || !want) none("set UPGRADE_TAG and UPGRADE_SHA256 to offer one");
  else {
    const { execSync } = await import("child_process"); const git = (c) => execSync("git " + c, { stdio: "pipe" }).toString().trim();
    let code = null; try { code = fs.readFileSync(wasmPath); } catch {}
    const sha = code ? (await import("crypto")).createHash("sha256").update(code).digest("hex") : "";
    let atTag = false; try { atTag = git(`rev-parse ${tag}^{commit}`) === git("rev-parse HEAD"); } catch {}
    if (!atTag) none(`HEAD is not the commit of ${tag}`);
    else if (!code) none("no build at " + wasmPath.pathname);
    else if (sha !== want) none(`the build's sha256 ${sha} is not the published ${want}`);
    else {
      const notes = process.env.UPGRADE_NOTES || "Release " + tag + ".";
      fs.writeFileSync(out, "// Generated by site/tools/make-site-data.mjs from the tagged release " + tag + " (sha256 checked).\nwindow.MS_UPGRADE = " + JSON.stringify({ hash: "0x1220" + sha, tag, notes, size: code.length }) + ";\nwindow.MS_UPGRADE.code = \"" + code.toString("base64") + "\";\n");
      console.log("wrote site/station-code.js (" + tag + ", sha256 " + sha + ")");
    }
  }
}
